                "inf_model, idx_to_species, species_meta = build_inference_pipeline()\n",
                "\n",
                "def predict_and_visualize(audio_path: str, top_k: int = 3):\n",
                "    p = Path(audio_path)\n",
                "    if not p.exists(): p = Path(\"..\") / audio_path\n",
                "    if not p.exists():\n",
                "        print(f\"File not found: {audio_path}\")\n",
                "        return\n",
                "        \n",
                "    y, sr = librosa.load(str(p), sr=32000, mono=True)\n",
                "    dur = len(y) / sr\n",
                "    \n",
                "    # Multi-window energy selection\n",
                "    w = int(sr * 5.0)\n",
                "    if len(y) <= w:\n",
                "        clips = [np.tile(y, int(np.ceil(w / len(y))))[:w]]\n",
                "    else:\n",
                "        hop = int(sr * 1.0)\n",
                "        windows = [y[s : s + w] for s in range(0, len(y) - w + 1, hop)]\n",
                "        energies = [np.sqrt(np.mean(seg**2)) for seg in windows]\n",
                "        top_idx = np.argsort(energies)[::-1][:3]\n",
                "        clips = [windows[i] for i in top_idx]\n",
                "        \n",
                "    # Extract Log-Mels\n",
                "    tensors = []\n",
                "    for c in clips:\n",
                "        pk = np.max(np.abs(c))\n",
                "        if pk > 1e-8: c = (c / pk) * 0.95\n",
                "        mel = librosa.feature.melspectrogram(y=c, sr=sr, n_fft=2048, hop_length=512, win_length=2048, n_mels=128, fmin=50.0, fmax=14000.0, power=2.0)\n",
                "        mel_db = librosa.power_to_db(mel, ref=np.max, top_db=80.0)\n",
                "        mel_db = np.nan_to_num(mel_db, nan=-80.0, posinf=0.0, neginf=-80.0)\n",
                "        mel_norm = (mel_db - mel_db.mean()) / (mel_db.std() + 1e-6)\n",
                "        tensors.append(torch.from_numpy(mel_norm).float().unsqueeze(0).repeat(3, 1, 1).unsqueeze(0))\n",
                "        \n",
                "    batch_tensors = torch.cat(tensors, dim=0).to(DEVICE)\n",
                "    with torch.no_grad():\n",
                "        probs = torch.softmax(inf_model(batch_tensors), dim=1).mean(dim=0).cpu().numpy()\n",
                "        \n",
                "    top_cands = np.argsort(probs)[::-1][:top_k]\n",
                "    \n",
                "    # Visualization\n",
                "    fig, axes = plt.subplots(1, 2, figsize=(15, 4))\n",
                "    im = axes[0].imshow(mel_db, origin='lower', aspect='auto', cmap='magma')\n",
                "    axes[0].set_title(f\"Primary Vocalization Spectrogram: {p.name} ({dur:.1f}s)\", fontsize=11, fontweight='bold')\n",
                "    axes[0].set_xlabel(\"Time Frame\")\n",
                "    axes[0].set_ylabel(\"Mel Bin\")\n",
